// Turns a BYO definition (from env or the console) into a catalog entry.
export function byoToModel(def) {
  return {
    id: def.id || `byo-${(def.model || "custom").replace(/[^a-z0-9]+/gi, "-").toLowerCase()}`,
    name: def.name || def.model,
    lab: def.lab || "Your endpoint",
    tier: "slm",
    runtime: "byo",
    model: def.model,
    baseURL: def.baseURL,
    apiKeyEnv: def.apiKeyEnv,
    ctx: def.ctx || 32_000,
    price: def.price || { in: 0, out: 0 },
    quality: def.quality || 5.5,
    speed: def.speed || 7,
    fit: { ...f(5, 5, 5, 2, 6, 7, 6), ...(def.fit || {}) },
    strengths: def.strengths || "Your own model, called through an OpenAI-compatible endpoint.",
    byo: true,
  };
}
